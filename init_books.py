with app.app_context():
    genre_by_name = {}

    for genre_name in GENRES:
        genre = Genre.query.filter_by(name=genre_name).first()
        if genre is None:
            genre = Genre(name=genre_name)
            db.session.add(genre)
            db.session.flush()
        genre_by_name[genre_name] = genre

    added = 0

    for title, description, year, publisher, author, pages, genre_names in BOOKS:
        book = Book.query.filter_by(title=title).first()

        if book is None:
            book = Book(
                title=title,
                description=description,
                year=year,
                publisher=publisher,
                author=author,
                pages=pages,
            )

            book.genres = [genre_by_name[name] for name in genre_names]
            db.session.add(book)
            added += 1

    db.session.commit()

    print(f"Готово. Добавлено новых книг: {added}.")
    print(f"Всего книг в базе: {Book.query.count()}.")
    print("Если книг больше 10, на главной странице появится пагинация.")
